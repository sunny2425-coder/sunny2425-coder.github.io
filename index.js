const revealObserver = new IntersectionObserver(
  (entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  },
  {
    threshold: 0.12,
    rootMargin: "0px 0px -40px 0px"
  }
);

revealElements.forEach((element) => revealObserver.observe(element));

const heroSection = document.querySelector(".hero");
const heroVisual = document.querySelector(".hero-visual");

if (heroSection && heroVisual) {
  heroSection.addEventListener("mousemove", (event) => {
    const rectangle = heroSection.getBoundingClientRect();
    const horizontalPosition =
      (event.clientX - rectangle.left) / rectangle.width - 0.5;
    const verticalPosition =
      (event.clientY - rectangle.top) / rectangle.height - 0.5;

    heroVisual.style.transform = `
      translate3d(
        ${horizontalPosition * 14}px,
        ${verticalPosition * 14}px,
        0
      )
    `;
  });

  heroSection.addEventListener("mouseleave", () => {
    heroVisual.style.transform = "translate3d(0, 0, 0)";
  });
}

const counters = document.querySelectorAll(".counter");
const counterObserver = new IntersectionObserver(
  (entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;

      const counter = entry.target;
      const target = Number(counter.dataset.target || 0);
      const suffix = counter.dataset.suffix || "";
      const duration = 1200;
      const startTime = performance.now();

      function updateCounter(currentTime) {
        const progress = Math.min((currentTime - startTime) / duration, 1);
        const currentValue = Math.floor(progress * target);
        counter.textContent = `${currentValue}${suffix}`;

        if (progress < 1) {
          requestAnimationFrame(updateCounter);
        }
      }

      requestAnimationFrame(updateCounter);
      observer.unobserve(counter);
    });
  },
  { threshold: 0.5 }
);

counters.forEach((counter) => counterObserver.observe(counter));

const imageModal = document.getElementById("imageModal");
const imageModalContent = document.getElementById("imageModalContent");
const imageModalClose = document.getElementById("imageModalClose");

document.querySelectorAll(".image-view-button").forEach((button) => {
  button.addEventListener("click", () => {
    const imagePath = button.dataset.image;
    if (!imagePath || !imageModal || !imageModalContent) return;

    imageModalContent.src = imagePath;
    imageModal.classList.add("open");
    imageModal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  });
});

function closeImageModal() {
  if (!imageModal || !imageModalContent) return;
  imageModal.classList.remove("open");
  imageModal.setAttribute("aria-hidden", "true");
  imageModalContent.src = "";
  document.body.style.overflow = "";
}

imageModalClose?.addEventListener("click", closeImageModal);

imageModal?.addEventListener("click", (event) => {
  if (event.target === imageModal) closeImageModal();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && imageModal?.classList.contains("open")) {
    closeImageModal();
  }
});
